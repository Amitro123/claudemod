"""Copies src/greeter/templates to plugins/greeter/templates. --check exits 1 on drift."""
import pathlib, sys
SRC = pathlib.Path("src/greeter/templates")
DST = pathlib.Path("plugins/greeter/templates")
drift = []
for f in SRC.glob("*"):
    target = DST / f.name
    if "--check" in sys.argv:
        if not target.exists() or target.read_text() != f.read_text():
            drift.append(str(target))
    else:
        DST.mkdir(parents=True, exist_ok=True)
        target.write_text(f.read_text())
if drift:
    print("DRIFT in:", ", ".join(drift))
    sys.exit(1)
FIXEOF
